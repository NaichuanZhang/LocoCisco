const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const containers = new Map();
const document = { getElementById(id) { if (!containers.has(id)) containers.set(id, {innerHTML: ''}); return containers.get(id); }, addEventListener() {} };
const context = { document, window: {}, setInterval() {}, console };
vm.createContext(context);
vm.runInContext(fs.readFileSync(process.argv[2], 'utf8'), context);
const view = context.window.LocoPresenter;
const html = id => containers.get(id).innerHTML;
const all = () => [...containers.values()].map(c => c.innerHTML).join('\n');
let id = 0;
const emit = (topic, data, epoch=0) => view.event({ id: `test-${++id}`, topic, data, ts: id, stream_epoch: epoch });
const roles = ['vad','asr','diarization','faces','asd','decider','llm'];
view.snapshot({ privacy: {state:'on'}, models: roles.map(role => ({role, ok: true})), settings:{act_threshold:.6,ask_threshold:.4}, participants:[], items:[] });
assert.match(html('model-summary'), /7 \/ 7 models ready/);
assert.doesNotMatch(html('model-pipeline'), /is-working/);
emit('sensor.telemetry',{audio:{start:1,end:2,asr_ms:93,diar_ms:12,voice:'voice-A',voice_conf:.8},vision:{t:2,face_count:1,faces:[{track_id:'f1',bbox:[.2,.3,.1,.2],speaking:.7}]},counts:{segments:1,frames:25}});
assert.match(html('model-summary'), /93 ms/);
assert.match(html('capture-vision'), /left:20%/);
emit('meeting.utterance',{utterance_id:'u1',text:'Private <img src=x onerror=alert(1)>',speaker:{name:'Test Person',guest:false}});
assert.match(html('decision-detail'), /&lt;img/);
assert.doesNotMatch(html('decision-detail'), /<img/);
const pId=`test-${id+1}`;
emit('meeting.proposal',{utterance_id:'u1',route:'local-decider',mode:'shadow',action:'create_task',confidence:.5,probabilities:{create_task:.5,none:.3,log_decision:.2},threshold:.6,latency_ms:310});
assert.match(html('model-pipeline'), /is-working/);
emit('meeting.proposal',{utterance_id:'u1',route:'local-llm',mode:'act',action:'none',latency_ms:420,confidence:.9,confidence_source:'adapter_constant',tool_calls:[]});
assert.match(html('decision-detail'), /730 ms model time/);
assert.match(html('decision-detail'), /not a calibrated model probability/);
emit('meeting.verdict',{proposal_id:`test-${id}`,action:'none',verdict:'ignore',rule:'Not a commitment',risk:'low'});
assert.match(html('capture-feed'), /No action/);
emit('meeting.privacy',{state:'off_record'},2);
assert.doesNotMatch(all(), /Private &lt;img|Test Person|Not a commitment|f1/);
assert.match(html('decision-detail'), /Off the record/);
emit('meeting.utterance',{utterance_id:'stale',text:'STALE SECRET'},1);
emit('sensor.telemetry',{audio:{end:9,asr_ms:9999},counts:{segments:9,frames:9}},1);
assert.doesNotMatch(all(), /STALE SECRET|9999/);
emit('meeting.privacy',{state:'on'},3);
assert.doesNotMatch(all(), /Private &lt;img|Test Person/);
view.replay({generation:4,privacy_epoch:5,privacy:'off_record'});
view.snapshot({demo:{generation:4,privacy_epoch:4,privacy:'on'},privacy:{state:'on'},participants:[{name:'STALE PERSON'}],items:[{text:'STALE ITEM'}]});
assert.doesNotMatch(all(), /STALE PERSON|STALE ITEM/);
view.reset();
view.snapshot({demo:{generation:0,privacy_epoch:0,privacy:'on'},privacy:{state:'on'},models:roles.map(role=>({role,ok:true})),items:[]});
emit('meeting.utterance',{utterance_id:'new',text:'Fresh current utterance'},0);
assert.match(html('decision-detail'),/Fresh current utterance/);
view.privacy('paused');
assert.match(html('decision-detail'),/Notes paused/);
assert.doesNotMatch(all(),/Fresh current utterance/);
console.log('Presenter contract checks passed: real values, escaped text, no fabricated busy state, privacy clearing, stale epochs, stale replay snapshots, and restarted server.');

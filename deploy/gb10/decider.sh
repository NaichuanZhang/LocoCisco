#!/usr/bin/env bash
# deploy/gb10/decider.sh 12b|2b [--dry-run] [--stop] [--status]
#
# Strands Decider on the GB10 GPU, loopback only.
#   12b -> 127.0.0.1:8765  StrandsAgents/strands-decider-12B-gemma4-v1-2610 over google/gemma-4-12B-it (~23 GB bf16)
#   2b  -> 127.0.0.1:8766  StrandsAgents/strands-decider-2B-qwen3.5-v1-2610 over Qwen/Qwen3.5-2B-Base  (~4.5 GB bf16)
#
# Runtime (DECIDER_RUNTIME):
#   docker  (default) the pinned NVIDIA vLLM image's own CUDA-13 / aarch64 / sm_121 torch (it is on the box
#                     anyway: NemoClaw runs it). strands-decider + deps come from the USB wheelhouse
#                     ($DECIDER_WHEELS, pure-Python wheels, no torch) into a per-image user site under
#                     $UNSPOKEN_STATE on first start (~1 min), then cached. Alternative torso:
#                     DECIDER_IMAGE=nvcr.io/nvidia/pytorch:26.09-py3 (same recipe).
#   native            a host venv: DECIDER_BIN=/path/to/strands-decider (restore.sh builds one from the
#                     torch-cu130 wheels as the no-docker fallback; on the dev desktop it is the CPU proof).
#
# Env: DECIDER_DEVICE=cuda|cpu (default cuda)   DECIDER_PORT (override the port)   DECIDER_MAX_BATCH (default 8)
#      DECIDER_IMAGE (default $IMAGE_VLLM)      DECIDER_WHEELS (default $UNSPOKEN_MODELS/wheels/decider)
#      DECIDER_EXTRA="..." extra strands-decider serve flags   NO_GPU=1 drops --gpus all (tests)
# Health: curl -s 127.0.0.1:8765/health ; ask: POST /v1/systemone {"state":..., "questions":{...}}

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
parse_common_flags "$@"
set -- "${ARGS[@]+"${ARGS[@]}"}"

SIZE="${1:-}"; shift || true
ACTION=start
for a in "$@"; do case "$a" in --stop) ACTION=stop ;; --status) ACTION=status ;; *) die "unknown flag $a" ;; esac; done

case "$SIZE" in
  12b) REPO="$DECIDER_12B_REPO"; BASE="$DECIDER_12B_BASE"; PORT="${DECIDER_PORT:-$PORT_DECIDER_12B}" ;;
  2b)  REPO="$DECIDER_2B_REPO";  BASE="$DECIDER_2B_BASE";  PORT="${DECIDER_PORT:-$PORT_DECIDER_2B}" ;;
  *) usage; exit 2 ;;
esac

RUNTIME="${DECIDER_RUNTIME:-docker}"
DEVICE="${DECIDER_DEVICE:-cuda}"
IMAGE="${DECIDER_IMAGE:-$IMAGE_VLLM}"
WHEELS="${DECIDER_WHEELS:-$UNSPOKEN_MODELS/wheels/decider}"
MAX_BATCH="${DECIDER_MAX_BATCH:-8}"
NAME="unspoken-decider-$SIZE"
LOG="$UNSPOKEN_LOGS/decider-$SIZE.log"
STATE="$UNSPOKEN_STATE/decider"
PIDFILE="$STATE/$NAME.pid"
HEALTH="http://127.0.0.1:$PORT/health"

status() {
  if [ "$DRY_RUN" = 1 ]; then printf '+ curl -fsS %s\n' "$HEALTH" >&2; return 0; fi
  if curl -fsS -m 3 "$HEALTH" 2>/dev/null; then echo; ok "decider $SIZE answers on :$PORT"; return 0; fi
  fail "decider $SIZE not answering on :$PORT"; return 1
}

stop() {
  if [ "$RUNTIME" = docker ]; then docker_rm_if_exists "$NAME"
  elif [ -f "$PIDFILE" ]; then run kill "$(cat "$PIDFILE")" || true; [ "$DRY_RUN" = 1 ] || rm -f "$PIDFILE"
  else warn "no pid file $PIDFILE"; fi
}

# The entry script that runs inside the container (also readable in --dry-run output).
entry_script() {
  cat <<EOF
#!/usr/bin/env bash
# generated by deploy/gb10/decider.sh for $NAME
set -euo pipefail
export HOME=/state PYTHONUSERBASE=/state/pyuser PIP_DISABLE_PIP_VERSION_CHECK=1 PIP_NO_CACHE_DIR=1
export HF_HOME=/hf HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_HUB_DISABLE_TELEMETRY=1 TOKENIZERS_PARALLELISM=false
mkdir -p /state/pyuser
exec > >(tee -a "/logs/decider-$SIZE.log") 2>&1
echo "== \$(date -Is) $NAME image=$IMAGE device=$DEVICE"
# first start only: strands-decider and its pure-Python deps from the USB wheelhouse (no torch: the image's torch stays)
if [ ! -x /state/pyuser/bin/strands-decider ] || [ /wheels/requirements.txt -nt /state/pyuser/.installed ]; then
  env -u PIP_CONSTRAINT -u PIP_BUILD_CONSTRAINT python3 -m pip install --user --break-system-packages --no-index --no-deps --find-links /wheels -r /wheels/requirements.txt
  touch /state/pyuser/.installed
fi
python3 - <<'PY'
import torch
dev = torch.cuda.get_device_name(0) if torch.cuda.is_available() else "no cuda"
print(f"torch {torch.__version__} cuda={torch.cuda.is_available()} {dev}")
PY
CKPT=\$(ls -1dt /hf/hub/models--${REPO//\//--}/snapshots/* | head -1)
echo "checkpoint \$CKPT (base $BASE from the HF cache, offline)"
exec /state/pyuser/bin/strands-decider serve "\$CKPT" --host 127.0.0.1 --port $PORT --device $DEVICE \\
  --model-name decider-$SIZE --max-batch $MAX_BATCH ${DECIDER_EXTRA:-}
EOF
}

start_docker() {
  need docker
  if docker_running "$NAME"; then ok "$NAME already running"; status; return; fi
  docker_rm_if_exists "$NAME"
  mkdirs; [ "$DRY_RUN" = 1 ] || mkdir -p "$STATE"
  [ -d "$WHEELS" ] || [ "$DRY_RUN" = 1 ] || die "wheelhouse missing: $WHEELS (run deploy/usb/restore.sh)"
  [ "$DRY_RUN" = 1 ] || hf_cached "$REPO" || die "adapter not in HF cache: $REPO (run deploy/usb/restore.sh)"
  [ "$DRY_RUN" = 1 ] || hf_cached "$BASE" || die "base model not in HF cache: $BASE"
  if [ "$DRY_RUN" = 1 ]; then log "entry script ($STATE/$NAME.sh):"; entry_script | sed 's/^/    /' >&2
  else entry_script > "$STATE/$NAME.sh"; chmod +x "$STATE/$NAME.sh"; fi
  # shellcheck disable=SC2046
  run docker run -d --pull=never --name "$NAME" --restart unless-stopped --network host $(gpu_flag) \
    --user "$(id -u):$(id -g)" --ipc host \
    -v "$UNSPOKEN_HF_HOME:/hf" -v "$WHEELS:/wheels:ro" -v "$STATE:/state" -v "$UNSPOKEN_LOGS:/logs" \
    --entrypoint bash "$IMAGE" "/state/$NAME.sh"
  wait_http "$HEALTH" "${DECIDER_WAIT:-600}" "decider $SIZE" || { docker logs --tail 40 "$NAME" >&2 || true; exit 1; }
  status
}

start_native() {
  local bin="${DECIDER_BIN:-$UNSPOKEN_STATE/decider-venv/bin/strands-decider}"
  [ -x "$bin" ] || [ "$DRY_RUN" = 1 ] || die "strands-decider not found at $bin (set DECIDER_BIN or run restore.sh)"
  if [ -f "$PIDFILE" ] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then ok "$NAME already running (pid $(cat "$PIDFILE"))"; status; return; fi
  mkdirs; [ "$DRY_RUN" = 1 ] || mkdir -p "$STATE"
  local ckpt; ckpt="$(hf_snapshot "$REPO")"
  [ -n "$ckpt" ] || [ "$DRY_RUN" = 1 ] || die "adapter not in HF cache: $REPO"
  export HF_HOME="$UNSPOKEN_HF_HOME" HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_HUB_DISABLE_TELEMETRY=1 TOKENIZERS_PARALLELISM=false
  if [ "$DEVICE" = cpu ]; then export OMP_NUM_THREADS="${OMP_NUM_THREADS:-12}"; fi
  # shellcheck disable=SC2086
  run_sh "nohup $(printf '%q' "$bin") serve $(printf '%q' "${ckpt:-<snapshot of $REPO>}") --host 127.0.0.1 --port $PORT --device $DEVICE --model-name decider-$SIZE --max-batch $MAX_BATCH ${DECIDER_EXTRA:-} > $(printf '%q' "$LOG") 2>&1 </dev/null & echo \$! > $(printf '%q' "$PIDFILE")"
  wait_http "$HEALTH" "${DECIDER_WAIT:-600}" "decider $SIZE" || { tail -40 "$LOG" >&2 || true; exit 1; }
  status
}

case "$ACTION" in
  status) status ;;
  stop) stop ;;
  start)
    log "decider $SIZE: $REPO on $DEVICE via $RUNTIME -> 127.0.0.1:$PORT"
    case "$RUNTIME" in
      docker) start_docker ;;
      native) start_native ;;
      *) die "DECIDER_RUNTIME must be docker or native" ;;
    esac ;;
esac
